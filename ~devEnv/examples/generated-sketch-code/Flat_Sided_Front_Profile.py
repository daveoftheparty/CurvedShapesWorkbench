import FreeCAD as app
import Sketcher, Part

def createSketch_Flat_Sided_Front_Profile(doc):
    Flat_Sided_Front_Profile = doc.addObject('Sketcher::SketchObject', 'Flat_Sided_Front_Profile')
    geo0 = Flat_Sided_Front_Profile.addGeometry(Part.LineSegment(Vector (-4.0, -5.0, 0.0), Vector (4.0, -5.0, 0.0)))
    Flat_Sided_Front_Profile.toggleConstruction(geo0)
    geo1 = Flat_Sided_Front_Profile.addGeometry(Part.LineSegment(Vector (4.0, -5.0, 0.0), Vector (4.0, 5.0, 0.0)))
    Flat_Sided_Front_Profile.toggleConstruction(geo1)
    geo2 = Flat_Sided_Front_Profile.addGeometry(Part.LineSegment(Vector (4.0, 5.0, 0.0), Vector (-4.0, 5.0, 0.0)))
    Flat_Sided_Front_Profile.toggleConstruction(geo2)
    geo3 = Flat_Sided_Front_Profile.addGeometry(Part.LineSegment(Vector (-4.0, 5.0, 0.0), Vector (-4.0, -5.0, 0.0)))
    Flat_Sided_Front_Profile.toggleConstruction(geo3)
    geo4 = Flat_Sided_Front_Profile.addGeometry(Part.Point(Vector(-0.0, -0.0, 0.0)))
    Flat_Sided_Front_Profile.toggleConstruction(geo4)
    geo5 = Flat_Sided_Front_Profile.addGeometry(Part.ArcOfCircle(Part.Circle(Vector(0.0, -1.7137884072761502, 0.0), Vector (0.0, 0.0, 1.0), 3.2862115927238498), 3.2901830214447942, 6.134594939324585))
    geo6 = Flat_Sided_Front_Profile.addGeometry(Part.ArcOfCircle(Part.Circle(Vector(0.0, -3.5000000000000004, 0.0), Vector (0.0, 0.0, 1.0), 8.5), 1.2030598901251002, 1.9385327634634626))
    geo7 = Flat_Sided_Front_Profile.addGeometry(Part.LineSegment(Vector (-4.0, 2.809938199485819, 0.0), Vector (-3.2499999999999996, -2.2002929110092886, 0.0)))
    geo8 = Flat_Sided_Front_Profile.addGeometry(Part.LineSegment(Vector (4.0, 2.8099381994860955, 0.0), Vector (3.249999999999999, -2.200292911009289, 0.0)))
    geo9 = Flat_Sided_Front_Profile.addGeometry(Part.ArcOfCircle(Part.Circle(Vector(-2.5165288775701584, 3.0320044709381633, 0.0), Vector (0.0, 0.0, 1.0), 1.5), 1.9385327634636262, 3.290183021444784))
    geo10 = Flat_Sided_Front_Profile.addGeometry(Part.ArcOfCircle(Part.Circle(Vector(2.5165288775700403, 3.032004470937678, 0.0), Vector (0.0, 0.0, 1.0), 1.5), 6.13459493932511, 7.486245197298824))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Coincident', geo0, 2, geo1, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Coincident', geo1, 2, geo2, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Coincident', geo2, 2, geo3, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Coincident', geo3, 2, geo0, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Horizontal', geo0))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Horizontal', geo2))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Vertical', geo1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Vertical', geo3))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Symmetric', geo2, 1, geo0, 1, geo4, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Coincident', geo4, 1, -1, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('DistanceY', geo3, 2, geo3, 1, 10.0))
    Flat_Sided_Front_Profile.renameConstraint(10, 'Height')
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('DistanceX', geo2, 2, geo2, 1, 8.0))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('PointOnObject', geo5, 3, -2))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Horizontal', geo5, 2, geo5, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Tangent', geo5, 0, geo0))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('DistanceX', geo5, 1, geo5, 2, 6.5))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Coincident', geo8, 2, geo5, 2))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Tangent', geo6, 0, geo2))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Tangent', geo7, 2, geo5, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Radius', geo6, 8.5))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Tangent', geo7, 1, geo9, 2))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Tangent', geo6, 2, geo9, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Tangent', geo8, 1, geo10, 1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Tangent', geo6, 1, geo10, 2))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('PointOnObject', geo6, 3, -2))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('PointOnObject', geo7, 1, geo3))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('PointOnObject', geo8, 1, geo1))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Radius', geo9, 1.5))
    Flat_Sided_Front_Profile.addConstraint(Sketcher.Constraint('Equal', geo9, geo10))
    Flat_Sided_Front_Profile.AttacherEngine = 'Engine Plane'
    Flat_Sided_Front_Profile.setExpression('Constraints[11]', '.Constraints.Height * 0.8')
    Flat_Sided_Front_Profile.setExpression('Constraints[15]', '.Constraints.Height * 0.65')
    Flat_Sided_Front_Profile.Placement = Placement(Vector(0.0, 0.0, 0.0), Rotation (0.7071067811865476, 0.0, 0.0, 0.7071067811865475))
    Flat_Sided_Front_Profile.Visibility = False
    Flat_Sided_Front_Profile.ViewObject.Visibility = False
    return Flat_Sided_Front_Profile

def make_doc():
    doc = app.newDocument('bait_to_copy')
    Flat_Sided_Front_Profile = createSketch_Flat_Sided_Front_Profile(doc)
    doc.recompute()

make_doc()